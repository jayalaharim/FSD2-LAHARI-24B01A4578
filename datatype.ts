//string datatype
let str1 = "Hello World!";
console.log(str1);
let str2 = "Have a good day";
console.log(str2);
let str3 = "Hi!";
console.log(str3+"\n");

//number datatype
let int1 = 10;
console.log(int1);
let int2 = 25;
console.log(int2);
let int3 = 100;
console.log(int3+"\n");

//boolean datatype
let bool1 = true;
console.log(bool1);
let bool2 = false;
console.log(bool2);
let bool3 = 10 > 5;
console.log(bool3+"\n");

//null datatype
let null1 = null;
console.log(null1+"\n");

// bigint datatype
let big1 = 12345678901234567890n;
console.log(big1);
let big2 = 9876543210123456789n;
console.log(big2);
let big3 = 99999999999n;
console.log(big3+"\n");

//symbol datatype
let sym1 = Symbol("id");
console.log(sym1);
let sym2 = Symbol("user");
console.log(sym2);
let sym3 = Symbol("code");
console.log(sym3);